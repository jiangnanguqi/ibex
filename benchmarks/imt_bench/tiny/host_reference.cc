#include "model_runner.h"
#include <cstdio>
#include <cstring>

int main() {
  using namespace imt_tiny;
  const int status = Initialize();
  if (status) {
    std::fprintf(stderr, "TFLM initialization failed: %d\n", status);
    return status;
  }
  std::printf("// Generated by host_reference; do not edit.\n"
              "#ifndef IMT_TINY_GOLDEN_H_\n#define IMT_TINY_GOLDEN_H_\n"
              "#include <cstdint>\nnamespace imt_tiny {\n"
              "static const int8_t kExpected[3][640] = {\n");
  uint32_t scores[kFixtureCount];
  for (int sample = 0; sample < kFixtureCount; ++sample) {
    if (PrepareInput(sample) || Invoke()) return 10;
    std::printf("{");
    for (size_t i = 0; i < OutputBytes(); ++i) {
      if (i % 20 == 0) std::printf("\n");
      std::printf("%d,", static_cast<int>(Output()[i]));
    }
    std::printf("\n},\n");
    scores[sample] = FloatBits(AnomalyScore(sample));
    std::fprintf(stderr, "fixture=%d output_bytes=%zu hash=%08x score=%.9g arena=%zu\n",
                 sample, OutputBytes(), OutputHash(), AnomalyScore(sample),
                 ArenaBytesUsed());
  }
  std::printf("};\nstatic const uint32_t kExpectedScoreBits[3] = {");
  for (int i = 0; i < kFixtureCount; ++i) std::printf("0x%08xu,", scores[i]);
  std::printf("};\n}  // namespace imt_tiny\n#endif\n");
  if (PrepareInput(0) || Invoke()) return 11;
  int8_t first_output[kInputElements];
  std::memcpy(first_output, Output(), sizeof(first_output));
  const uint32_t first_hash = OutputHash();
  if (Invoke()) return 12;
  const uint32_t repeated_hash = OutputHash();
  std::fprintf(stderr, "repeated_inference first_hash=%08x next_hash=%08x\n",
               first_hash, repeated_hash);
  if (std::memcmp(first_output, Output(), sizeof(first_output)) != 0) return 13;
  return 0;
}

