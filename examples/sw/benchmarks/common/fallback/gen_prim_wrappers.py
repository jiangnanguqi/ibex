"""Write the abstract primitive wrappers that FuseSoC's primgen generator
would produce when only the generic technology library is present.

Each wrapper prim_<name> instantiates prim_generic_<name> inside a generate
block 'gen_generic' as 'u_impl_generic', the same hierarchy as primgen's
output, so that Simple System's memory loader finds the RAM at
TOP.ibex_simple_system.u_ram.u_ram.gen_generic.u_impl_generic.

Usage: gen_prim_wrappers.py <prim_generic rtl dir> <output dir>
"""
import pathlib
import re
import sys

PRIMS = ['buf', 'flop', 'clock_gating', 'ram_1p', 'ram_2p']


def wrapper(name, source):
    match = re.search(r'module\s+prim_generic_%s\s*(.*?)\);' % name, source, re.S)
    header = match.group(1)
    imports = ''
    found = re.match(r'\s*(import\s+[^;]+;)', header)
    if found:
        imports = found.group(1)
        header = header[found.end():]
    parameters = re.match(r'\s*#\((.*?)\)\s*\((.*)', header, re.S)
    if parameters:
        params, ports = parameters.group(1), parameters.group(2)
    else:
        params, ports = '', re.match(r'\s*\((.*)', header, re.S).group(1)
    names = re.findall(r'^\s*parameter\s+(?:[\w:$\[\]\s]+?\s)?(\w+)\s*=', params, re.M)
    if names:
        instance = ('    prim_generic_%s #(\n' % name +
                    ',\n'.join('      .%s(%s)' % (p, p) for p in names) +
                    '\n    ) u_impl_generic (\n      .*\n    );\n')
    else:
        instance = '    prim_generic_%s u_impl_generic (\n      .*\n    );\n' % name
    return ('// Generated by gen_prim_wrappers.py: primgen-style abstract wrapper.\n'
            '`include "prim_assert.sv"\n'
            'module prim_%s %s' % (name, imports) +
            ('#(%s) (' % params if parameters else '(') + ports + ');\n' +
            '  if (1) begin : gen_generic\n' + instance + '  end\nendmodule\n')


def main():
    generic_dir, out_dir = map(pathlib.Path, sys.argv[1:3])
    out_dir.mkdir(parents=True, exist_ok=True)
    for name in PRIMS:
        text = wrapper(name, (generic_dir / ('prim_generic_%s.sv' % name)).read_text())
        (out_dir / ('prim_%s.sv' % name)).write_text(text)


if __name__ == '__main__':
    main()
